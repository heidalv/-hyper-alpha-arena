def _matches_system_prefix(flag: str) -> bool:
    return any(flag.startswith(p) for p in SYSTEM_PREFIXES)


def _is_falsy(val: str) -> bool:
    return val.strip().lower() in ("", "0", "false", "no", "off", "disabled", "disable")


def find_unknown_flags(env: dict[str, str] | None = None) -> list[str]:
    """返回当前 env 中"匹配系统前缀但未登记"的 flag 列表。"""
    env = env if env is not None else os.environ
    unknown: list[str] = []
    for key in env:
        if not key.isupper():
            continue
        if not _matches_system_prefix(key):
            continue
        if key not in KNOWN_FLAGS:
            unknown.append(key)
    return sorted(unknown)


def find_silently_disabled_safety_flags(env: dict[str, str] | None = None) -> list[str]:
    """返回被设为 falsy 的安全关键 flag（这些若非有意应告警）。"""
    env = env if env is not None else os.environ
    disabled: list[str] = []
    for flag in SAFETY_CRITICAL_FLAGS:
        if flag in env and _is_falsy(env[flag]):
            disabled.append(flag)
    return sorted(disabled)


def validate_strict(env: dict[str, str] | None = None, *, on_unknown: str | None = None) -> None:
    """
    启动期调用。扫描 env，对未知/静默禁用的 flag 按策略处理。

    on_unknown: 'warn' (默认) | 'error' (硬失败，CI/生产用) | 'silent'。
                未传时读 ENV_STRICT=error 则 error，否则 warn。
    """
    if on_unknown is None:
        on_unknown = "error" if os.environ.get("ENV_STRICT", "").lower() == "error" else "warn"

    unknown = find_unknown_flags(env)
    disabled_safety = find_silently_disabled_safety_flags(env)

    if disabled_safety:
        logger.warning(
            "[EnvRegistry] ⚠️ 安全关键 flag 被设为关闭（请确认是有意为之）: %s",
            ", ".join(disabled_safety),
        )

    if unknown:
        msg = (
            f"[EnvRegistry] 发现 {len(unknown)} 个匹配系统前缀但未登记的 env-flag（"
            f"疑似拼写错误/遗留/静默禁用）: {', '.join(unknown[:20])}"
            f"{' ...' if len(unknown) > 20 else ''}. "
            f"请登记到 config.env_registry.KNOWN_FLAGS 或修正拼写。"
        )
        if on_unknown == "error":
            logger.error(msg)
            raise SystemExit(f"ENV_STRICT=error: {msg}")
        elif on_unknown == "warn":
            logger.warning(msg)
        # silent: 不输出


def scan_codebase_for_flags(root: str | None = None) -> set[str]:
    """
    静态扫描 backend/**/*.py，提取所有 os.environ/os.getenv 读取的 flag 名。
    用于周期性补全 KNOWN_FLAGS（不自动写入，输出候选供人工审核）。
    """
    root = root or os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    pattern = re.compile(
        r'(?:os\.environ(?:\.get)?|os\.getenv|getenv|getenvbool|getenvint|get_flag|getenv_list)'
        r'\(\s*["\']([A-Z_][A-Z0-9_]{3,})["\']'
    )
    flags: set[str] = set()
    for dirpath, dirnames, filenames in os.walk(root):
        # skip venv/cache
        dirnames[:] = [d for d in dirnames if d not in {'.venv', '__pycache__', '.git', 'node_modules'}]
        for fn in filenames:
            if not fn.endswith('.py'):
                continue
            try:
                with open(os.path.join(dirpath, fn), encoding='utf-8', errors='ignore') as f:
                    flags.update(pattern.findall(f.read()))
            except OSError:
                continue
    return flags


def _cli() -> int:
    """`python -m backend.config.env_registry --scan` 输出候选 flag 清单。"""
    if '--scan' in sys.argv:
        found = scan_codebase_for_flags()
        registered = set(KNOWN_FLAGS)
        missing = sorted(found - registered)
        print(f"# 代码中引用但未登记的 env-flag（候选补全到 KNOWN_FLAGS）：{len(missing)}")
        for f in missing:
            print(f"    \"{f}\",")
        print(f"\n# 已登记：{len(registered)}，代码引用：{len(found)}，待审核：{len(missing)}")
        return 0
    if '--check' in sys.argv:
        unknown = find_unknown_flags()
        disabled = find_silently_disabled_safety_flags()
        print(f"未知系统 flag: {len(unknown)}")
        for f in unknown:
            print(f"  ? {f} = {os.environ.get(f)}")
        print(f"被关闭的安全 flag: {len(disabled)}")
        for f in disabled:
            print(f"  ⚠ {f}")
        return 0 if not unknown else 1
    print("用法: python -m backend.config.env_registry --scan | --check")
    return 0


if __name__ == "__main__":
    sys.exit(_cli())
